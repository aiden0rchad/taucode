it("drags continuously, then commits and animates to the nearest supported stop", () => {
  vi.stubGlobal("PointerEvent", MouseEvent);
  const change = vi.fn();
  const { rerender } = render(<ReasoningControl capability={cap} value="low" onChange={change} />);
  fireEvent.click(screen.getByRole("button", { name: "Reasoning: Low" }));
  const slider = screen.getByRole("slider");
  const dialog = screen.getByRole("dialog");
  vi.spyOn(slider, "getBoundingClientRect").mockReturnValue({ left: 0, width: 236 } as DOMRect);
  let captured = false;
  slider.setPointerCapture = () => { captured = true; };
  slider.hasPointerCapture = () => captured;
  slider.releasePointerCapture = () => { captured = false; };
  expect(dialog.querySelectorAll(".reasoning-sparkle")).toHaveLength(10);
  fireEvent.pointerDown(slider, { clientX: 108, button: 0 });
  expect(dialog.classList.contains("dragging")).toBe(true);
  expect(dialog.style.getPropertyValue("--reasoning-position")).toBe("45%");
  fireEvent.pointerMove(slider, { clientX: 148 });
  expect(dialog.style.getPropertyValue("--reasoning-position")).toBe("65%");
  expect(change).not.toHaveBeenCalled();
  fireEvent.pointerUp(slider, { clientX: 148 });
  expect(change).toHaveBeenCalledWith("high");
  rerender(<ReasoningControl capability={cap} value="high" onChange={change} />);
  expect(dialog.classList.contains("dragging")).toBe(false);
  expect(dialog.style.getPropertyValue("--reasoning-position")).toBe("50%");
  expect(slider.getAttribute("aria-valuetext")).toBe("High");
  fireEvent.keyDown(slider, { key: "Home" });
  expect(change).toHaveBeenLastCalledWith("low");
  fireEvent.keyDown(slider, { key: "End" });
  expect(change).toHaveBeenLastCalledWith("max");
});
