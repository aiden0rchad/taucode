import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { once } from "node:events";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { registerStreamRecovery } from "../extensions/lib/streamRecovery.ts";

test("root streams retain only display evidence, flush and clean up after persisted completion", t => {
  const dir = mkdtempSync(join(tmpdir(), "taucode-stream-")), session = join(dir, "session.jsonl");
  writeFileSync(session, "original session");
  const handlers = new Map<string, (event: any, ctx: any) => void>();
  registerStreamRecovery({ on: (name: string, handler: any) => handlers.set(name, handler) } as never);
  let leaf = "user";
  const ctx = { sessionManager: { getSessionFile: () => session, getLeafId: () => leaf } };
  const emit = (type: string, event: any) => handlers.get(type)?.(event, ctx);
  t.after(() => { emit("agent_end", {}); rmSync(dir, { recursive: true, force: true }); });
  emit("message_start", { message: { role: "assistant", timestamp: 2 } });
  emit("message_update", { message: { role: "assistant", timestamp: 2, content: [{ type: "text", text: "Partial" }] } });
  leaf = "unrelated-entry-during-stream";
  emit("message_update", { message: { role: "assistant", timestamp: 2, content: [{ type: "text", text: "Latest partial" }, { type: "toolCall", id: "unexecuted" }] } });
  emit("message_end", { message: { role: "assistant" } });
  emit("tool_execution_update", { toolName: "bash", toolCallId: "call/../../unsafe", partialResult: { content: [{ type: "text", text: "TOOL_READY" }] } });
  emit("tool_execution_update", { toolName: "subagent", toolCallId: "delegate", partialResult: {} });
  emit("tool_execution_update", { toolName: "bash", toolCallId: "nested", parentToolCallId: "parent", partialResult: {} });
  emit("tool_execution_end", { toolCallId: "call/../../unsafe" });
  const files = readdirSync(`${session}.streams`);
  assert.equal(files.length, 2);
  const saved = files.map(file => JSON.parse(readFileSync(join(`${session}.streams`, file), "utf8")));
  assert.deepEqual(saved.find(s => s.anchor)?.result.content, [{ type: "text", text: "Latest partial" }]);
  assert.equal(saved.find(s => s.anchor)?.anchor, "user", "anchor is captured before streaming");
  assert.equal(saved.find(s => s.toolCallId)?.result.content[0].text, "TOOL_READY");
  assert.equal(readFileSync(session, "utf8"), "original session", "no model-context writes");
  emit("agent_end", {});
  assert.deepEqual(readdirSync(`${session}.streams`), []);
  emit("agent_start", {});
  leaf = "next-user";
  emit("message_start", { message: { role: "assistant", timestamp: 3 } });
  emit("message_update", { message: { role: "assistant", timestamp: 3, content: [{ type: "text", text: "Before abort" }] } });
  emit("message_end", { message: { role: "assistant", stopReason: "aborted" } });
  emit("agent_end", {});
  assert.equal(readdirSync(`${session}.streams`).length, 1, "aborts retain evidence even when the runtime saves an empty final message");
  emit("agent_start", {});
  leaf = "follow-up";
  emit("message_start", { message: { role: "assistant", timestamp: 4 } });
  emit("message_update", { message: { role: "assistant", timestamp: 4, content: [{ type: "text", text: "Normal follow-up" }] } });
  emit("agent_end", {});
  assert.equal(readdirSync(`${session}.streams`).length, 1, "a later successful turn removes only its own checkpoints");
});

test("a killed root writer preserves assistant text and ordinary tool output", { skip: process.platform === "win32" }, async t => {
  const dir = mkdtempSync(join(tmpdir(), "taucode-stream-kill-")), session = join(dir, "session.jsonl");
  const child = spawn(process.execPath, ["--input-type=module", "-e", `
    import { registerStreamRecovery } from ${JSON.stringify(new URL("../extensions/lib/streamRecovery.ts", import.meta.url).href)};
    const handlers = new Map(); registerStreamRecovery({on:(name, handler)=>handlers.set(name,handler)});
    const ctx = {sessionManager:{getSessionFile:()=>${JSON.stringify(session)},getLeafId:()=>"user"}};
    const message = {role:"assistant",timestamp:2,content:[{type:"text",text:"ROOT_PARTIAL"}]};
    handlers.get("message_start")({message},ctx); handlers.get("message_update")({message},ctx);
    handlers.get("tool_execution_update")({toolName:"bash",toolCallId:"call",partialResult:{content:[{type:"text",text:"TOOL_PARTIAL"}]}},ctx);
    process.stdout.write("ready"); setInterval(()=>{},1000);
  `], { stdio: ["ignore", "pipe", "pipe"] });
  t.after(() => { child.kill("SIGKILL"); rmSync(dir, { recursive: true, force: true }); });
  const ready = await Promise.race([once(child.stdout, "data"), once(child, "exit").then(() => { throw new Error("stream writer exited before ready"); })]);
  assert.equal(String(ready[0]), "ready");
  const exited = once(child, "exit"); child.kill("SIGKILL"); await exited;
  const saved = readdirSync(`${session}.streams`).map(file => readFileSync(join(`${session}.streams`, file), "utf8")).join();
  assert.match(saved, /ROOT_PARTIAL/); assert.match(saved, /TOOL_PARTIAL/);
});
